(function (root) {
  'use strict';
  // Personal "Duty Record" PDF generator for the Duty In Charge feature.
  // Flat vector layout (no templates, no signatures). Runs in the browser and in node.

  function getLib() {
    if (root.PDFLib) return root.PDFLib;
    if (typeof require !== 'undefined') {
      try { return require('../vendor/pdf-lib.min.js'); } catch (e) {}
    }
    throw new Error('pdf-lib is not loaded.');
  }

  const PAGE_W = 595;
  const PAGE_H = 842;
  const X_DATE = 60;
  const X_ACT = 200;
  const X_HOURS_RIGHT = 530;
  const RULE_X = 60;
  const RULE_W = 470;
  const RULE_H = 0.6;
  const TITLE_Y = 782;
  const SUB_Y = 760;
  const HDR_Y = 716;
  const PREV_Y = 696;
  const ROW_FIRST_Y = 676;
  const ROW_LAST_Y = 136;
  const ROW_H = 20;
  const FOOTER_Y = 40;
  const TABLE_SIZE = 9;

  function formatHours(v) {
    const n = Number(v);
    if (!isFinite(n)) return '0';
    return Number.isInteger(n) ? String(n) : String(Math.round(n * 100) / 100);
  }

  function truncate(str, max) {
    const s = String(str == null ? '' : str);
    return s.length > max ? s.slice(0, max - 1) + '\u2026' : s;
  }

  // Helvetica/WinAnsi cannot encode CJK; map unsupported characters to '?'
  // instead of failing — only an unconfirmed Previous may block generation.
  const pdfText = value => String(value == null ? '' : value).replace(/[^\u0020-\u007E\u00A0-\u00FF\u2013\u2014\u2018\u2019\u201C\u201D\u2026]/g, '?');

  async function generateDutyRecord(report) {
    if (!report || !report.member || report.year == null || report.year === '') {
      throw new Error('Duty record report must include member and year.');
    }
    if (!report.confirmed) {
      throw new Error('Previous balance is not confirmed yet.');
    }
    const PDFLib = getLib();
    const { PDFDocument, rgb, StandardFonts } = PDFLib;
    const doc = await PDFDocument.create();
    const font = await doc.embedFont(StandardFonts.Helvetica);
    const bold = await doc.embedFont(StandardFonts.HelveticaBold);
    const black = rgb(0, 0, 0);
    const grey = rgb(0.4, 0.4, 0.4);

    const member = report.member;
    const year = pdfText(report.year);
    const name = pdfText(member.name);
    const sjamId = (member.sjamId == null || member.sjamId === '') ? '-' : pdfText(member.sjamId);
    const lines = Array.isArray(report.lines) ? report.lines : [];

    const rule = (page, y) => {
      page.drawRectangle({ x: RULE_X, y: y, width: RULE_W, height: RULE_H, color: black });
    };

    const drawRight = (page, text, y, fnt, size, color) => {
      const w = fnt.widthOfTextAtSize(text, size);
      page.drawText(text, { x: X_HOURS_RIGHT - w, y: y, size: size, font: fnt, color: color });
    };

    const drawHeader = (page) => {
      page.drawText('Date', { x: X_DATE, y: HDR_Y, size: TABLE_SIZE, font: bold, color: black });
      page.drawText('Activity', { x: X_ACT, y: HDR_Y, size: TABLE_SIZE, font: bold, color: black });
      drawRight(page, 'Hours', HDR_Y, bold, TABLE_SIZE, black);
      rule(page, HDR_Y - 6);
    };

    const drawFooter = (page) => {
      page.drawText('Generated by TCCD Member System \u2014 private document', {
        x: X_DATE, y: FOOTER_Y, size: 8, font: font, color: grey
      });
    };

    // First page: title, sub line, table header, opening balance row.
    let page = doc.addPage([PAGE_W, PAGE_H]);
    drawFooter(page);
    page.drawText('Duty Record ' + year, { x: X_DATE, y: TITLE_Y, size: 16, font: bold, color: black });
    page.drawText('Name: ' + name, { x: X_DATE, y: SUB_Y, size: 10, font: font, color: black });
    page.drawText('SJAM ID: ' + sjamId, { x: 330, y: SUB_Y, size: 10, font: font, color: black });
    drawHeader(page);
    // Previous row: rule above (header rule) and below makes it read as the opening balance.
    page.drawText('Previous', { x: X_DATE, y: PREV_Y, size: TABLE_SIZE, font: font, color: black });
    drawRight(page, formatHours(report.previousTotal), PREV_Y, font, TABLE_SIZE, black);
    rule(page, PREV_Y - 6);

    let y = ROW_FIRST_Y;
    for (let i = 0; i < lines.length; i++) {
      if (y < ROW_LAST_Y) {
        page = doc.addPage([PAGE_W, PAGE_H]);
        drawFooter(page);
        drawHeader(page);
        y = ROW_FIRST_Y;
      }
      const line = lines[i] || {};
      page.drawText(pdfText(line.date), { x: X_DATE, y: y, size: TABLE_SIZE, font: font, color: black });
      page.drawText(truncate(pdfText(line.activityName), 40), { x: X_ACT, y: y, size: TABLE_SIZE, font: font, color: black });
      drawRight(page, formatHours(line.hours), y, font, TABLE_SIZE, black);
      rule(page, y - 6);
      y -= ROW_H;
    }

    // Totals right after the last row (Previous row when there are no detail lines).
    const lastY = lines.length === 0 ? PREV_Y : y + ROW_H;
    const subtotalY = lastY - ROW_H;
    const cumulativeY = lastY - 2 * ROW_H;
    page.drawText('Subtotal ' + year, { x: X_DATE, y: subtotalY, size: TABLE_SIZE, font: font, color: black });
    drawRight(page, formatHours(report.subtotal), subtotalY, font, TABLE_SIZE, black);
    rule(page, subtotalY - 6);
    page.drawText('Cumulative total', { x: X_DATE, y: cumulativeY, size: TABLE_SIZE, font: bold, color: black });
    drawRight(page, formatHours(report.cumulative), cumulativeY, bold, TABLE_SIZE, black);
    rule(page, cumulativeY - 6);

    return doc.save();
  }

  async function downloadDutyRecord(report) {
    const bytes = await generateDutyRecord(report);
    const safeName = String(report.member.name == null ? '' : report.member.name).replace(/[^A-Za-z0-9_-]/g, '_');
    const fileName = 'Duty-Record-' + report.year + '-' + safeName + '.pdf';
    if (typeof Blob !== 'undefined' && typeof document !== 'undefined') {
      const blob = new Blob([bytes], { type: 'application/pdf' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url; a.download = fileName;
      document.body.appendChild(a); a.click(); document.body.removeChild(a);
      setTimeout(() => URL.revokeObjectURL(url), 60000);
    }
    return bytes;
  }

  root.KPTDutyPDF = { generateDutyRecord, downloadDutyRecord };
  if (typeof module !== 'undefined' && module.exports) module.exports = root.KPTDutyPDF;
})(typeof globalThis !== 'undefined' ? globalThis : this);
